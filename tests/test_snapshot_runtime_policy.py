"""Deferred snapshots obey the same runtime policy as replay.

A deferred snapshot is a native read of the original run's Domain state. It
must not be regenerated by a different ViennaPS/ViennaLS runtime than the run
that produced it.
"""
from __future__ import annotations

import asyncio
import json
import secrets
import subprocess
import sys
import unittest
from pathlib import Path

from backend import snapshots as snapshot_store
from backend import storage
from backend.engine import EngineVersionMismatch, installed_version_map
from backend.main import app
from tests.test_api_integration import asgi_request, json_body
from tests.test_materials_milestone import project as materials_project, step as materials_step

ROOT = Path(__file__).resolve().parents[1]

def foreign_versions() -> dict[str, str]:
    installed = installed_version_map()
    if installed["viennaps"] != "4.6.2":
        return {"viennaps": "4.6.2", "viennals": "5.8.5"}
    return {"viennaps": "4.7.0", "viennals": "5.10.0"}


class DeferredSnapshotRuntimePolicy(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        storage.initialize()
        self.life = app.router.lifespan_context(app)
        await self.life.__aenter__()

    async def asyncTearDown(self):
        await self.life.__aexit__(None, None, None)

    def fake_run(self, required: dict[str, str]) -> tuple[str, Path, str]:
        run_id = secrets.token_hex(12)
        step_id = "step_policy"
        run_dir = storage.run_path(run_id)
        run_dir.mkdir(parents=True)
        (run_dir / "input.json").write_text(json.dumps({
            "kind": "simulate", "runId": run_id, "expectedVersions": required,
            "project": {"schemaVersion": 7, "dimension": 2},
        }), encoding="utf-8")
        (run_dir / "manifest.json").write_text(json.dumps({
            "status": "succeeded", "snapshots": [{"stepId": step_id, "outputs": []}],
        }), encoding="utf-8")
        (run_dir / f"{step_id}.meta.json").write_text(json.dumps({
            "metadata": {"name": "policy", "stepIndex": 0, "outputs": []},
        }), encoding="utf-8")
        (run_dir / f"state-{step_id}.vpsd").write_bytes(b"not-a-real-state")
        return run_id, run_dir, step_id

    def assert_policy_detail(self, detail: dict, required: dict[str, str]) -> None:
        self.assertEqual(detail["requiredVersions"], required)
        self.assertEqual(detail["installedVersions"], installed_version_map())
        self.assertIn("never reinterpreted", detail["message"])
        self.assertIn(required["viennaps"], detail["message"])
        self.assertIn(installed_version_map()["viennaps"], detail["message"])

    async def test_deferred_snapshot_get_is_rejected_for_a_foreign_runtime(self):
        required = foreign_versions()
        run_id, run_dir, step_id = self.fake_run(required)

        response = await asgi_request(f"/api/runs/{run_id}/snapshots/{step_id}")
        self.assertEqual(response[0], 409, response[2].decode("utf-8", errors="replace"))
        self.assert_policy_detail(json_body(response)["detail"], required)
        self.assertFalse((run_dir / f"{step_id}.json").is_file())

    async def test_run_download_is_rejected_for_a_foreign_runtime(self):
        required = foreign_versions()
        run_id, run_dir, step_id = self.fake_run(required)

        response = await asgi_request(f"/api/runs/{run_id}/download")
        self.assertEqual(response[0], 409, response[2].decode("utf-8", errors="replace"))
        self.assert_policy_detail(json_body(response)["detail"], required)
        self.assertFalse((run_dir / f"{step_id}.json").is_file())

    async def test_direct_materialize_raises_the_typed_policy_error(self):
        required = foreign_versions()
        _run_id, run_dir, step_id = self.fake_run(required)
        with self.assertRaises(EngineVersionMismatch) as raised:
            snapshot_store.ensure_materialized(run_dir, step_id)
        self.assertEqual(raised.exception.required_versions, required)
        self.assertIn("never reinterpreted", str(raised.exception))

    async def test_materialize_worker_rejects_before_reading_state(self):
        required = foreign_versions()
        _run_id, run_dir, step_id = self.fake_run(required)
        completed = subprocess.run(
            [sys.executable, str(ROOT / "worker" / "materialize_snapshot.py"),
             str(run_dir / "input.json"), str(run_dir), step_id],
            cwd=ROOT, capture_output=True, text=True, timeout=60, check=False)
        self.assertNotEqual(completed.returncode, 0)
        self.assertIn("never reinterpreted", completed.stderr)
        self.assertIn(required["viennaps"], completed.stderr)
        self.assertFalse((run_dir / f"{step_id}.json").is_file())

    async def wait(self, run_id: str) -> dict:
        for _ in range(1200):
            info = json_body(await asgi_request(f"/api/runs/{run_id}"))
            if info["status"] in {"succeeded", "failed", "cancelled", "timed_out", "interrupted"}:
                self.assertEqual(info["status"], "succeeded", info.get("failureReason"))
                return info
            await asyncio.sleep(0.05)
        self.fail("bounded native worker exceeded acceptance timeout")

    async def test_matching_runtime_deferred_snapshot_still_materializes(self):
        value = materials_project(2)
        value["steps"] = [materials_step("isotropic", "etch", rate=0.2)]
        response = await asgi_request("/api/runs", method="POST",
                                      payload={"kind": "simulate", "project": value})
        self.assertEqual(response[0], 202, response[2])
        run_id = json_body(response)["runId"]
        info = await self.wait(run_id)
        step_id = info["snapshots"][-1]["stepId"]
        run_dir = storage.run_path(run_id)
        self.assertTrue((run_dir / f"{step_id}.meta.json").is_file())
        self.assertFalse((run_dir / f"{step_id}.json").is_file())

        served = await asgi_request(f"/api/runs/{run_id}/snapshots/{step_id}")
        self.assertEqual(served[0], 200, served[2][:300])
        self.assertTrue((run_dir / f"{step_id}.json").is_file())


if __name__ == "__main__":
    unittest.main()
